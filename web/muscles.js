function muscleText(value) {
  return String(value ?? "").replace(/[&<>"']/g, (ch) => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
  }[ch]));
}

function renderAnatomy(selectedId) {
  const selected = MUSCLES.find((item) => item.id === selectedId);
  const card = selected
    ? `<h3>${muscleText(selected.name)}</h3><p><b>作用</b> ${muscleText(selected.job)}</p><p><b>训练它是为了</b> ${muscleText(selected.plan)}</p>`
    : "<p>点一块肌肉。这里会写出它的作用，以及训练它是为了什么。</p>";
  const deep = MUSCLES.filter((item) => item.view === "deep").map((item) =>
    `<button type="button" data-muscle="${item.id}">${muscleText(item.name)}</button>`,
  ).join("");
  return `<h2>肌肉图</h2>
    <p class="small">正面和背面按站立时的位置来画。左右是同一块肌肉。引线旁边是名字。深层的几块在表面上看不全，放在图下面。</p>
    <div class="anatomy">
      ${figure("front", "正面", selectedId)}
      ${figure("back", "背面", selectedId)}
      <div class="box muscle-card">${card}</div>
    </div>
    <p class="small">表面挂图上看不到整块的：</p>
    <div class="actions">${deep}</div>`;
}

function figure(view, title, selectedId) {
  const shapes = MUSCLES.filter((item) => item.view === view)
    .sort((a, b) => (a.z || 0) - (b.z || 0))
    .map((item) => renderMuscle(item, selectedId))
    .join("");
  return `<div>
    <p class="small">${title}</p>
    <svg viewBox="0 0 340 660" class="figure" role="img" aria-label="${title}肌肉图">
      ${view === "front" ? skinFront() : skinBack()}
      ${shapes}
    </svg>
  </div>`;
}

function renderMuscle(item, selectedId) {
  const on = item.id === selectedId ? " on" : "";
  const parts = (item.paths || []).map((d) => `<path class="part" d="${d}" />`).join("");
  const seams = (item.seams || []).map((d) => `<path class="seam" d="${d}" />`).join("");
  const leader = item.leader ? `<path class="leader" d="${item.leader}" />` : "";
  const anchor = item.label && item.label.anchor === "end" ? "end" : "start";
  const label = item.label
    ? `<text x="${item.label.x}" y="${item.label.y}" text-anchor="${anchor}">${muscleText(item.name)}</text>`
    : "";
  return `<g class="muscle${on}" data-muscle="${item.id}" style="--c:${item.fill || "#e7b2a6"}">${parts}${seams}${leader}${label}</g>`;
}

